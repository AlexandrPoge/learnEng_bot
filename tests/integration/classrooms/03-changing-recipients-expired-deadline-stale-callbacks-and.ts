import { harness } from './helpers.js';
import { test } from 'node:test';
import assert from 'node:assert/strict';

test('changing recipients, expired deadline, stale callbacks and revoked roles cannot assign', () => {
  const h = harness();
  const { state, send, press, click, last } = h;
  const c = h.makeClass();
  send(10, '/my_homework');
  press(10, 'тему учебника');
  h.seek(10, 'To be');
  press(10, '3 класс');
  press(10, 'Через 1');
  press(10, 'Тренировка');
  const confirm = last(10).reply_markup!.inline_keyboard![0][0].callback_data!;
  c.studentIds.pop();
  press(10, 'Назначить');
  assert.equal(Object.values(state.assignments ?? {}).length, 0);
  click(10, confirm);
  assert.equal(Object.values(state.assignments ?? {}).length, 0);
  send(10, '/my_homework');
  press(10, 'тему учебника');
  h.seek(10, 'To be');
  press(10, 'User 20');
  send(10, '2099-02-30T18:00+03:00');
  assert.match(last(10).text!, /Нужна будущая дата/u);
  send(10, '2099-11-20T18:00+03:00');
  press(10, 'Тренировка');
  const pending = state.users['10'].workspace;
  assert.equal(pending?.kind, 'assign');
  if (pending?.kind === 'assign') pending.deadline = '2000-01-01T00:00:00.000Z';
  press(10, 'Назначить');
  assert.equal(Object.values(state.assignments ?? {}).length, 0);
  send(10, '/my_homework');
  press(10, 'тему учебника');
  h.seek(10, 'To be');
  press(10, 'User 20');
  press(10, 'Через 3');
  press(10, 'Тренировка');
  const nextConfirm = last(10).reply_markup!.inline_keyboard![0][0].callback_data!;
  send(99, '/remove_teacher 10');
  click(10, nextConfirm);
  assert.equal(Object.values(state.assignments ?? {}).length, 0);
});
