import { harness } from './helpers.js';
import { test } from 'node:test';
import assert from 'node:assert/strict';

test('class corrections, homework level and question editing work through buttons', () => {
  const h = harness();
  const { state, send, press } = h;
  const c = h.makeClass();
  send(10, '/classes');
  press(10, '3 класс');
  press(10, 'Название класса');
  send(10, 'Подростки');
  assert.equal(c.name, 'Подростки');
  press(10, 'Уровень класса');
  press(10, 'A2');
  assert.equal(c.level, 'A2');
  assert.deepEqual(c.lessonIds, ['present-simple']);
  press(10, 'Добавить темы');
  press(10, 'Present Simple');
  assert.deepEqual(c.lessonIds, []);
  const t = h.makeHomework();
  send(10, `/edit_homework ${t.id}`);
  press(10, 'Уровень');
  press(10, 'A2');
  press(10, 'Изменить вопросы');
  press(10, 'She ___');
  press(10, 'Заменить вопрос');
  press(10, 'Вписать ответ');
  send(10, 'He ___ happy.');
  send(10, 'is');
  send(10, 'He → is.');
  press(10, 'Изменить вопросы');
  press(10, 'I ___');
  press(10, 'Удалить из черновика');
  press(10, 'Опубликовать');
  const updated = state.homeworkTemplates![t.id].lesson;
  assert.equal(updated.level, 'A2');
  assert.equal(updated.questions.length, 1);
  assert.equal(updated.questions[0].prompt, 'He ___ happy.');
  press(10, 'Назначить');
  press(10, 'Себе');
  press(10, 'Через 1');
  press(10, 'Тренировка');
  press(10, 'Назначить');
  assert.equal(Object.values(state.assignments!)[0].studentId, '10');
});
